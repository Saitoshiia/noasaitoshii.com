const addressLabel = (event) => {
  if (typeof event.address === 'string' && event.address.trim()) return event.address
  if (!event.address) return 'Address not published'
  const label = [
    event.address.dataCenter,
    event.address.world,
    event.address.district,
    event.address.ward ? `Ward ${event.address.ward}` : null,
    event.address.plot ? `Plot ${event.address.plot}` : null,
  ].filter(Boolean).join(' · ')
  return label || 'Address not published'
}

export const projectGeneratedEvent = (event, authored = authoredEvents.find((candidate) => candidate.slug === event.slug)) => {
  const metaverse = event.eventType === 'ffxiv'
  const stream = event.eventType === 'stream'
  const hasVenue = Boolean(event.venueSlug || event.venueName || event.address)
  return {
    slug: event.slug,
    title: authored?.title || event.title,
    subtitle: authored?.subtitle || (stream ? 'Live on Twitch' : metaverse ? 'A Saitoshiia event' : 'An in-person appearance'),
    type: stream ? 'stream' : metaverse ? 'metaverse' : 'irl',
    startsAt: event.startsAtUtc,
    endsAt: event.endsAtUtc,
    noaStartsAt: event.noaStartsAtUtc,
    noaEndsAt: event.noaEndsAtUtc,
    eventTimeZone: event.eventTimeZone,
    venueSlug: event.venueSlug || null,
    venue: event.venueName || (stream ? 'Online' : 'Venue not published'),
    location: event.locationDisplay || (stream ? 'Online' : 'Location not published'),
    address: hasVenue ? addressLabel(event) : null,
    topic: event.topic || null,
    isLivestream: event.isLivestream === true,
    genre: stream ? null : event.genre?.join(' · ') || authored?.genre || 'Electronic',
    theme: event.theme || authored?.theme || null,
    status: event.status,
    cta: stream ? 'Watch the stream' : event.ticketUrl || event.eventInfoUrl ? 'Tickets & event information' : 'Stream & community',
    primaryUrl: event.ticketUrl || event.eventInfoUrl || event.streamUrl,
    streamUrl: event.streamUrl || null,
    secondaryUrl: metaverse ? 'https://discord.gg/saitoshiia' : null,
    lineupStatus: event.lineupStatus,
    lineup: event.lineup,
    setTimes: event.setTimes,
  }
}

const generatedEvents = (publicEventBundle.events || [])
  .filter((event) => event.audiences?.noaSaitoshii)
  .map((event) => projectGeneratedEvent(event))

const inGeneratedWindow = (event) => {
  const date = event.startsAt?.slice(0, 10)
  const { from, to } = publicEventBundle.sourceWindow || {}
  return Boolean(date && from && to && date >= from && date <= to)
}

export const events = [
  ...authoredEvents.filter((event) => !inGeneratedWindow(event)),
  ...generatedEvents,
]

const publicLifecycleStatuses = new Set(['upcoming', 'live', 'published', 'past', 'completed'])

export const getEffectiveEventStatus = (event, now = new Date()) => {
  if (!publicLifecycleStatuses.has(event.status)) return event.status
  if (['past', 'completed'].includes(event.status)) return 'past'

  const current = now instanceof Date ? now.getTime() : Date.parse(now)
  const startsAt = Date.parse(event.startsAt)
  const endsAt = Date.parse(event.endsAt)

  if (!Number.isFinite(current) || !Number.isFinite(startsAt) || !Number.isFinite(endsAt)) {
    return event.status
  }
  if (endsAt <= current) return 'past'
  if (startsAt <= current) return 'live'
  return 'upcoming'
}

export const projectEventLifecycle = (event, now = new Date()) => ({
  ...event,
  status: getEffectiveEventStatus(event, now),
})

export const getUpcomingEvents = (source = events, now = new Date()) => {
  return source
    .map((event) => projectEventLifecycle(event, now))
    .filter((event) => ['upcoming', 'live'].includes(event.status))
    .sort((a, b) => new Date(a.startsAt) - new Date(b.startsAt))
}

export const getPastEvents = (source = events, now = new Date()) => {
  return source
    .map((event) => projectEventLifecycle(event, now))
    .filter((event) => event.status === 'past')
    .sort((a, b) => new Date(b.startsAt) - new Date(a.startsAt))
}

export const getEventBySlug = (slug, source = events, now = new Date()) => {
  const event = source.find((candidate) => candidate.slug === slug)
  return event ? projectEventLifecycle(event, now) : undefined
}
